const courseTeachers: Record<string, string[]> = {
  "quran/muallim-sani": ["ali-yaushev", "ismail-shaykhutdinov"],
  "quran/muzakkara-tajvid": ["khamida-nazmutdinova"],
};

export function getCourseTeachers(subject: string, course: string): Teacher[] {
  const slugs = courseTeachers[`${subject}/${course}`] ?? subjectTeachers[subject] ?? [];
  return slugs.map(slug => teachers.find(teacher => teacher.slug === slug)!);
}

export const glossaryTeachers = teachers.filter(teacher => teacher.slug === "abu-akhmad");

export function teacherPath(teacher: Pick<Teacher, "slug">): string {
  return `/teachers/${teacher.slug}`;
}

export function teacherPerson(teacher: Teacher, site: URL | string) {
  const url = new URL(teacherPath(teacher), site).href;
  return {
    "@type": "Person",
    "@id": `${url}#person`,
    name: teacher.name,
    ...(teacher.fullName ? { alternateName: teacher.fullName } : {}),
    url,
    description: teacher.summary,
    knowsAbout: teacher.subjects,
  };
}
