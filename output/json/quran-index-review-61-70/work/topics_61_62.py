def topic_at(position):
    identity = original['topics'][position - 1]['id']
    return next(t for t in topics if t['id'] == identity)

def new_item(position, number, description):
    t = topic_at(position); identity = ident(position, number)
    assert identity not in items
    item = {'id': identity, 'description': description, 'relation_type': 'topic', 'verse_keys': []}
    t['items'].append(item); items[identity] = item; notes[identity] = {}
    topic_changes.append({'topic_id': t['id'], 'field': 'items', 'added_item_id': identity, 'reason': 'Выделено самостоятельное содержание: ' + description + '.'})
    return item

